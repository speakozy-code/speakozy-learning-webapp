/** Link a session's PDF opens: an admin-set web link wins, then the Drive default, then any older bundled path. */
export function pdfLinkFor(s: { id?: string; pdfUrl?: string } | null | undefined): string {
  const own = s?.pdfUrl || '';
  if (/^https?:\/\//i.test(own)) return own;
  return (s?.id && PDF_LINKS[s.id]) || own;
}
